/*
	here we have the normalised angle function. it's used to make sure the angle is between 0 and 2pi
*/

double	normalised_angle(double angle)
{
	if (angle < 0)
		angle += 2.0 * PI;
	if (angle >= 2.0 * PI)
		angle -= 2.0 * PI;
	return (angle);
}

